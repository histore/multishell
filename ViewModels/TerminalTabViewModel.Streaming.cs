using System;
using System.Text;
using System.Threading;
using MultiShell.Models;
using MultiShell.Services;

namespace MultiShell.ViewModels;

public partial class TerminalTabViewModel
{
    private readonly StringBuilder _pendingUiFeedBuffer = new();
    private readonly StringBuilder _inputLineBuffer = new();
    private readonly Lock _inputLineBufferLock = new();
    private TerminalUiFeedCoordinator? _uiFeedCoordinator;
    private bool _previousWasCr;

    private TerminalUiFeedCoordinator UiFeedCoordinator => _uiFeedCoordinator!;

    /// <summary>
    /// Indicates whether AltGr (Ctrl+Alt modifier) is currently pressed.
    /// Used to suppress false-positive Control characters generated by the terminal control during AltGr key combos.
    /// </summary>
    public bool IsAltGrActive { get; set; }

    /// <summary>
    /// Checks if incoming text from the shell contains terminal color queries (OSC 10 foreground, OSC 11 background)
    /// emitted by TUIs such as Neovim, and responds back to the shell with the active theme RGB colors.
    /// </summary>
    internal void CheckAndRespondToOscColorQueries(string text) =>
        TerminalUiFeedCoordinator.DispatchOscColorQueries(text, IsDarkTerminalTheme, _session);

    /// <summary>
    /// Strips unsupported OSC escape sequences (e.g. OSC 8 hyperlinks, OSC 9/133 shell integration)
    /// to prevent terminal controls from misparsing them and printing stray ']' characters at column 0.
    /// </summary>
    public static string SanitizeTerminalText(string text) =>
        AnsiStreamProcessor.SanitizeTerminalText(text);

    /// <summary>
    /// Finds the start index of an incomplete ANSI/VT100 escape sequence at the end of the text stream,
    /// or -1 if the text ends with complete escape sequences / plain characters.
    /// Used to buffer fragmented sequences across stream chunks and prevent color bleeding and render corruption.
    /// </summary>
    public static int FindIncompleteEscapeSequenceIndex(string text) =>
        AnsiStreamProcessor.FindIncompleteEscapeSequenceIndex(text);

    private void OnSessionDataReceived(ReadOnlyMemory<byte> data)
    {
        if (_isDisposed || data.IsEmpty) return;

        var initialPane = _initialPane;
        if (initialPane == null || ReferenceEquals(initialPane, ActivePane))
        {
            PulseOutputActivity();
        }
        UiFeedCoordinator.ProcessAndFeed(data.Span, IsDarkTerminalTheme, _session, TerminalModel, _dispatcherService);
    }

    /// <summary>
    /// Flushes all accumulated PTY stream chunks to the terminal model in a single batched pass on the UI thread.
    /// Eliminates TUI flicker caused by separate rendering of line-erase and text-write chunks.
    /// </summary>
    internal void FlushPendingUiFeed()
    {
        if (_isDisposed) return;
        UiFeedCoordinator.Flush(TerminalModel);
    }

    private void OnTerminalUserInput(object? sender, ReadOnlyMemory<byte> data)
    {
        if (!IsRunning || data.IsEmpty) return;

        var bytes = data.ToArray();

        // When AltGr (Ctrl+Alt) is active on international keyboards (e.g. AltGr+Q for '@', AltGr+E for '€'),
        // SvcSystems.UI.Terminal misidentifies the key as Ctrl+Q (0x11) / Ctrl+E (0x05) in OnKeyDown.
        // We filter out these single control bytes so only the valid TextInput character (@, €, etc.) is sent.
        if (IsAltGrActive && bytes.Length == 1 && bytes[0] < 32 && bytes[0] != 9 && bytes[0] != 10 && bytes[0] != 13)
        {
            return;
        }

        // Track user input line for live CommandHistory tracking
        TrackInputBuffer(bytes, _initialPane);

        _session.Send(bytes);
    }

    internal void TrackInputBuffer(byte[] bytes, TerminalPaneViewModel? sourcePane = null)
    {
        if (bytes.Length == 0 || bytes[0] == 0x1B) return;

        char[] chars;
        try
        {
            chars = Encoding.UTF8.GetChars(bytes);
        }
        catch (Exception ex) when (ex is ArgumentException or DecoderFallbackException)
        {
            System.Diagnostics.Debug.WriteLine($"[TerminalTabViewModel.TrackInputBuffer] UTF-8 decode failed: {ex.Message}");
            return;
        }

        var pane = sourcePane ?? ActivePane;
        var bufferLock = pane?.InputLineBufferLock ?? _inputLineBufferLock;
        lock (bufferLock)
        {
            foreach (var ch in chars)
            {
                ProcessInputBufferChar(ch, pane);
            }
        }

        UpdateDraftCommandState(pane);
    }

    private void ProcessInputBufferChar(char ch, TerminalPaneViewModel? pane)
    {
        var buffer = pane?.InputLineBuffer ?? _inputLineBuffer;
        bool previousWasCr = pane?.PreviousWasCr ?? _previousWasCr;

        if (ch == '\x03') // Ctrl+C -> cancel line
        {
            if (pane != null) pane.PreviousWasCr = false; else _previousWasCr = false;
            buffer.Clear();
            return;
        }

        if (ch == '\r') // Enter / Return: command execution
        {
            if (pane != null) pane.PreviousWasCr = true; else _previousWasCr = true;
            string executedCommand = buffer.ToString().Trim();
            buffer.Clear();
            RecordExecutedInputCommand(executedCommand, pane);
            return;
        }

        if (ch == '\n')
        {
            if (previousWasCr)
            {
                // CRLF sequence - already executed on '\r'
                if (pane != null) pane.PreviousWasCr = false; else _previousWasCr = false;
                return;
            }

            // Standalone linefeed (e.g. Shift+Enter / Ctrl+Enter multi-line script continuation)
            buffer.Append('\n');
            return;
        }

        if (pane != null) pane.PreviousWasCr = false; else _previousWasCr = false;

        if (ch == '\b' || ch == '\x7F') // Backspace
        {
            if (buffer.Length > 0)
            {
                buffer.Length--;
            }
            return;
        }

        if (!char.IsControl(ch))
        {
            buffer.Append(ch);
        }
    }

    private void RecordExecutedInputCommand(string executedCommand, TerminalPaneViewModel? sourcePane = null)
    {
        if (string.IsNullOrWhiteSpace(executedCommand)) return;

        var pane = sourcePane ?? ActivePane;
        var effectiveDir = !string.IsNullOrWhiteSpace(pane?.WorkingDirectory)
            ? pane.WorkingDirectory
            : WorkingDirectory;
        var effectiveShellType = pane?.ShellType ?? ShellType;

        MarkCommandStarted(executedCommand, pane);
        if (pane != null)
        {
            pane.PendingCommandDirectory = effectiveDir;
        }
        if (pane == null || ReferenceEquals(pane, ActivePane))
        {
            _pendingCommandDirectory = effectiveDir;
        }
        if (effectiveShellType != ShellType.PowerShell)
        {
            if (pane != null && !ReferenceEquals(TerminalModel, pane.TerminalModel))
            {
                HandlePaneCommandExecuted(pane, executedCommand);
            }
            else
            {
                OnSessionCommandExecuted(executedCommand);
            }
            CheckForDirectoryChangeCommand(executedCommand, pane);
        }
    }

    /// <summary>
    /// Synchronizes the HasDraftCommand property with the current content of the terminal input line buffer.
    /// </summary>
    internal void UpdateDraftCommandState(TerminalPaneViewModel? pane = null)
    {
        var targetPane = pane ?? ActivePane;
        var bufferLock = targetPane?.InputLineBufferLock ?? _inputLineBufferLock;
        var buffer = targetPane?.InputLineBuffer ?? _inputLineBuffer;

        bool hasDraft;
        lock (bufferLock)
        {
            hasDraft = buffer.Length > 0;
        }

        if (targetPane != null)
        {
            targetPane.HasDraftCommand = hasDraft;
        }

        if ((targetPane == null || ReferenceEquals(targetPane, ActivePane)) && HasDraftCommand != hasDraft)
        {
            _dispatcherService.RunOnUi(() => HasDraftCommand = hasDraft);
        }
    }

    /// <summary>
    /// Clears the input line buffer and updates draft command state.
    /// </summary>
    internal void ClearInputLineBuffer()
    {
        var pane = ActivePane;
        var bufferLock = pane?.InputLineBufferLock ?? _inputLineBufferLock;
        var buffer = pane?.InputLineBuffer ?? _inputLineBuffer;
        lock (bufferLock)
        {
            buffer.Clear();
        }
        UpdateDraftCommandState(pane);
    }

    private void OnTerminalSizeChanged(object? sender, (int Cols, int Rows) e)
    {
        if (!IsRunning) return;

        if (e.Cols > 0 && e.Rows > 0)
        {
            _session.Resize(e.Cols, e.Rows);
        }
    }
}
